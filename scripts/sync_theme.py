#!/usr/bin/env python3
"""Export NeuroLearn's canonical Flutter colors for the React applications."""

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "apps/neurolearn/app/lib/theme/app_theme.dart"
OUTPUT = ROOT / "packages/theme/neurolearn.css"


def render() -> str:
    palette = SOURCE.read_text(encoding="utf-8").split("class NeuroColors {", 1)[1].split("\n}", 1)[0]
    colors = re.findall(r"static const (\w+) = Color\(0xFF([A-Fa-f0-9]{6})\);", palette)
    if not colors:
        raise ValueError("NeuroColors has no exportable colors")
    tokens = []
    for name, value in colors:
        name = re.sub(r"[A-Z]", lambda m: "-" + m[0].lower(), name)
        tokens.append(f"  --neuro-{name}: #{value.upper()};")
    return (
        "/* Generated by scripts/sync_theme.py from NeuroColors. Do not edit. */\n"
        '@font-face {\n  font-family: "Source Sans 3";\n'
        '  src: url("../../apps/neurolearn/app/assets/fonts/SourceSans3.ttf") format("truetype");\n'
        "  font-style: normal;\n  font-weight: 200 900;\n  font-display: swap;\n}\n\n"
        ":root {\n" + "\n".join(tokens) + "\n}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            parser.exit(1, "Shared theme is stale. Run npm run sync:theme\n")
        print("Shared theme matches NeuroColors.")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
        print(f"Generated {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
